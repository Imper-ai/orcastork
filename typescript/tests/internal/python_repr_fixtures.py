def repr_rows() -> list[dict[str, str]]:
    rows: list[dict[str, str]] = []
    for row_id, document in REPR_ROWS:
        value = json.loads(document)
        expected = canonical_value(value)
        row = {'id': row_id, 'json': document, 'expected': expected}
        expected_js = canonical_value(as_js_number_domain(value))
        if expected_js != expected:
            row['expected_js'] = expected_js
        rows.append(row)
    return rows


def float_rows() -> list[dict[str, str]]:
    return [{'id': row_id, 'literal': literal, 'expected': repr(float(literal))} for row_id, literal in FLOAT_ROWS]


def str_rows() -> list[dict[str, str]]:
    rows: list[dict[str, str]] = []
    for row_id, document in STR_ROWS:
        value = json.loads(document)
        assert isinstance(value, str)
        rows.append({'id': row_id, 'json': document, 'expected': repr(value)})
    return rows


def main() -> None:
    import sys

    fixtures = {
        'generated_by': 'tests/internal/python_repr_fixtures.py',
        'python_version': sys.version.split()[0],
        'repr': repr_rows(),
        'float': float_rows(),
        'str': str_rows(),
    }
    destination = Path(__file__).with_name('python_repr_fixtures.json')
    destination.write_text(json.dumps(fixtures, indent=2, ensure_ascii=True) + '\n', encoding='utf-8')
    total = len(fixtures['repr']) + len(fixtures['float']) + len(fixtures['str'])
    print(f'wrote {total} fixtures to {destination}')


if __name__ == '__main__':
    main()
