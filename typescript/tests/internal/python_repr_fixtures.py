#!/usr/bin/env python3.13
"""Generate ``python_repr_fixtures.json`` — the CPython oracle for ``internal/python_repr.ts``.

The TypeScript ``pythonRepr`` has to reproduce ``repr(_make_hashable(value))`` byte for byte,
because that string is a Redis hash field and the input to the archive key's digest (see
``orcastork/datapoints/base.py`` and ``orcastork/archive/sealing.py``). The only honest oracle for
"what does CPython print" is CPython, so this script prints it, and the vitest suite asserts
against the table rather than against a second implementation of the rules.

Run it with Python 3.13 (stdlib only), from this directory::

    python3.13 python_repr_fixtures.py

Each value is carried in a form **both** runtimes parse identically:

``repr`` rows
    a JSON document. Python ``json.loads`` it, TypeScript ``JSON.parse``s it, and the two agree on
    every JSON-native value — except the one thing JavaScript cannot represent: it has a single
    number type, so a float whose value is integral is indistinguishable from the int. Those rows
    carry ``expected_js`` as well, which is the repr of the same value with every integral float
    replaced by that int — still CPython's repr, of a value adjusted by the one documented
    coercion, so the oracle is never a reimplementation of the port.

``float`` rows
    a decimal literal. ``float(literal)`` and ``Number(literal)`` produce the same double, so the
    formatting rules (shortest digits, the fixed-vs-exponent switch, the padded exponent, the
    infinities and NaN) are pinned without JSON's int/float ambiguity in the way.

``str`` rows
    a JSON string literal, so every escape is unambiguous on both sides.
"""

from __future__ import annotations

