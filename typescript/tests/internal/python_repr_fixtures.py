# Copied verbatim from ``orcastork/datapoints/base.py`` — the fixtures must be generated by the
# function under specification, not by a paraphrase of it.
def _make_hashable(obj: Any) -> Any:
    """Recursively coerce a value into a hashable form (lists/dicts/sets → tuples)."""
    if isinstance(obj, (list, tuple)):
        return tuple(_make_hashable(item) for item in obj)
    if isinstance(obj, dict):
        return tuple(sorted((key, _make_hashable(value)) for key, value in obj.items()))
    if isinstance(obj, (set, frozenset)):
        return tuple(sorted(_make_hashable(item) for item in obj))
    return obj


def canonical_value(value: Any) -> str:
    """The function under specification (``orcastork.datapoints.canonical_value``)."""
    return repr(_make_hashable(value))


def as_js_number_domain(obj: Any) -> Any:
    """The value as JavaScript can see it: one number type, and that type is a double.

    Two coercions, both of them inherent to the runtime and neither of them fixable: an integral
    float is indistinguishable from the int of the same value, and an int beyond 2**53 rounds to
    the nearest double. Applying them here and then taking CPython's own repr keeps the expectation
    an oracle rather than a second implementation of the port.
    """
    if isinstance(obj, bool):
        return obj
    if isinstance(obj, float) and math.isfinite(obj) and obj.is_integer():
        return int(obj)
    if isinstance(obj, int) and abs(obj) > 2**53:
        return int(float(obj))
    if isinstance(obj, list):
        return [as_js_number_domain(item) for item in obj]
    if isinstance(obj, dict):
        return {key: as_js_number_domain(value) for key, value in obj.items()}
    return obj


